import { describe, expect, it } from "vitest";
import type {
  BoostDef, DropDef, GameAssets, PlaceableDef, ZombieDef, ZombieModel,
} from "./assets";
import {
  looseMutationFiles, looseMutationPath, mergeSpecialZombieModel, raidRewardImage,
} from "./assets";

const assets = {
  drops: {
    Windmill: {
      icon: "wrong-loot-atlas-cell.png",
      brains: false,
      gold: false,
      tile: "windmill",
      unique: true,
      limit: 0,
    } satisfies DropDef,
    "Rusty Fragment": {
      icon: "rusty-fragment.png",
      brains: false,
      gold: false,
      tile: "",
      unique: false,
      limit: 3,
    } satisfies DropDef,
  },
  placeables: [{ key: "windmill", sprite: "windmill.png" } as PlaceableDef],
  boosts: [{ name: "Golden Dice", icon: "golden-dice.png" } as BoostDef],
} satisfies Pick<GameAssets, "drops" | "placeables" | "boosts">;

describe("raidRewardImage", () => {
  it("uses canonical object art for placeable raid rewards", () => {
    expect(raidRewardImage(assets, "Windmill")).toMatch(/assets\/objects\/windmill\.png$/);
  });

  it("keeps loot art for trophies and boost art for consumables", () => {
    expect(raidRewardImage(assets, "Rusty Fragment")).toMatch(/assets\/raids\/loot\/rusty-fragment\.png$/);
    expect(raidRewardImage(assets, "Golden Dice")).toMatch(/assets\/boosts\/golden-dice\.png$/);
  });
});

describe("loose mutation art", () => {
  // ZombieSheet.png + frames.json are generated by the asset pipeline, so mutation art
  // used to be invisible until someone repacked the atlas. Anything mutations.json
  // names that the sheet has no frame for is fetched as its own PNG instead.
  const atlas = { tomatoHead: {}, carrotHat: {} };
  const part = (file: string) => ({
    file, group: "head" as const, headRel: false, ox: 0, oy: 0, ax: 0, ay: 0, z: 0,
  });

  it("fetches only the parts the atlas does not already carry", () => {
    const parts = {
      "1": part("tomatoHead"), // packed
      "4": part("carrotHat"), // packed
      cornhead: part("cornhead.png"), // loose
      beethead: part("beethead"), // loose, extension omitted
    };
    expect(looseMutationFiles(parts, atlas).sort())
      .toEqual(["beethead", "cornhead.png"]);
  });

  it("dedupes parts that share one image", () => {
    const parts = { a: part("shared.png"), b: part("shared.png") };
    expect(looseMutationFiles(parts, atlas)).toEqual(["shared.png"]);
  });

  it("resolves a bare filename under assets/zombie/mutations/", () => {
    expect(looseMutationPath("cornhead.png")).toBe("mutations/cornhead.png");
    expect(looseMutationPath("cornhead")).toBe("mutations/cornhead.png");
  });

  it("takes a path with a folder as authored", () => {
    // So art kept in its own folder — including an existing mod's — resolves without
    // having to be moved or renamed.
    expect(looseMutationPath("modded_mutations/cornhead.png"))
      .toBe("modded_mutations/cornhead.png");
    expect(looseMutationPath("modded_mutations/cornhead"))
      .toBe("modded_mutations/cornhead.png");
  });
});

describe("mergeSpecialZombieModel", () => {
  // The named actors are attachment DELTAS over an ordinary skeleton, so what a merge
  // INHERITS is what decides whether a zombie ends up wearing two faces.
  const base: ZombieModel = {
    name: "base",
    neck: { x: 7, y: -36 },
    scale: 0.9,
    color: [159, 255, 95],
    parts: (
      ["defaultBody", "defaultHead", "defaultEyeL", "defaultEyeR", "defaultJaw",
        "defaultUpperTeeth", "defaultLowerTeeth", "defaultScar"] as const
    ).map((file, index) => ({
      file,
      group: file === "defaultBody" ? ("root" as const) : ("head" as const),
      px: 0, py: 0, ax: 0.5, ay: 0.5, z: index, tint: true,
    })),
  };
  const def = (key: string) => ({ key, name: key, group: "Regular" } as ZombieDef);
  const manifest = (...files: string[]) => ({
    name: "special",
    neck: { x: 7, y: -36 },
    parts: files.map((file) => ({
      file, group: "head" as const, px: 0, py: 0, ax: 0.5, ay: 0.5, z: 9,
    })),
  });
  const merged = (key: string, ...files: string[]) =>
    mergeSpecialZombieModel(base, def(key), manifest(...files), (file) => file)
      .parts.map((part) => part.file);

  it("keeps the ordinary face for an actor that only swaps its body", () => {
    expect(merged("ZombieActorSkittles", "Body.png")).toContain("defaultEyeL");
    expect(merged("ZombieActorSkittles", "Body.png")).toContain("defaultLowerTeeth");
  });

  it("drops the whole default face for an actor whose art already has one", () => {
    const parts = merged("ZombieActorMasterNinjombie", "Head.png");
    for (const face of ["defaultEyeL", "defaultEyeR", "defaultJaw",
      "defaultUpperTeeth", "defaultLowerTeeth", "defaultScar"]) {
      expect(parts).not.toContain(face);
    }
    expect(parts).toContain("Head.png");
  });

  it("drops only the mouth for a masked face, which keeps its eyes", () => {
    const parts = merged("ZombieActorZastronaut", "Features.png");
    expect(parts).not.toContain("defaultLowerTeeth");
    expect(parts).toContain("defaultEyeL");
    expect(parts).toContain("defaultHead");
  });

  it("drops the default lower teeth from any actor that brings its own jaw", () => {
    // They are positioned against the DEFAULT jaw and land wrong on another shape —
    // this is what put a second set of teeth on the Dapper Zombie's chin.
    const parts = merged("ZombieActorDapper", "Jaw.png");
    expect(parts).not.toContain("defaultLowerTeeth");
    expect(parts).toContain("defaultUpperTeeth");
  });
});
