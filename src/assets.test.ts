import { describe, expect, it } from "vitest";
import type { BoostDef, DropDef, GameAssets, PlaceableDef, ZombieDef } from "./assets";
import { looseMutationFiles, looseMutationPath, mergeModdedZombies, raidRewardImage } from "./assets";

const assets = {
  drops: {
    Windmill: {
      icon: "wrong-loot-atlas-cell.png",
      brains: false,
      gold: false,
      tile: "windmill",
      unique: true,
      limit: 0,
    } satisfies DropDef,
    "Rusty Fragment": {
      icon: "rusty-fragment.png",
      brains: false,
      gold: false,
      tile: "",
      unique: false,
      limit: 3,
    } satisfies DropDef,
  },
  placeables: [{ key: "windmill", sprite: "windmill.png" } as PlaceableDef],
  boosts: [{ name: "Golden Dice", icon: "golden-dice.png" } as BoostDef],
} satisfies Pick<GameAssets, "drops" | "placeables" | "boosts">;

describe("raidRewardImage", () => {
  it("uses canonical object art for placeable raid rewards", () => {
    expect(raidRewardImage(assets, "Windmill")).toMatch(/assets\/objects\/windmill\.png$/);
  });

  it("keeps loot art for trophies and boost art for consumables", () => {
    expect(raidRewardImage(assets, "Rusty Fragment")).toMatch(/assets\/raids\/loot\/rusty-fragment\.png$/);
    expect(raidRewardImage(assets, "Golden Dice")).toMatch(/assets\/boosts\/golden-dice\.png$/);
  });
});

describe("loose mutation art", () => {
  // ZombieSheet.png + frames.json are generated by the asset pipeline, so mutation art
  // used to be invisible until someone repacked the atlas. Anything mutations.json
  // names that the sheet has no frame for is fetched as its own PNG instead.
  const atlas = { tomatoHead: {}, carrotHat: {} };
  const part = (file: string) => ({
    file, group: "head" as const, headRel: false, ox: 0, oy: 0, ax: 0, ay: 0, z: 0,
  });

  it("fetches only the parts the atlas does not already carry", () => {
    const parts = {
      "1": part("tomatoHead"), // packed
      "4": part("carrotHat"), // packed
      cornhead: part("cornhead.png"), // loose
      beethead: part("beethead"), // loose, extension omitted
    };
    expect(looseMutationFiles(parts, atlas).sort())
      .toEqual(["beethead", "cornhead.png"]);
  });

  it("dedupes parts that share one image", () => {
    const parts = { a: part("shared.png"), b: part("shared.png") };
    expect(looseMutationFiles(parts, atlas)).toEqual(["shared.png"]);
  });

  it("adds authored facing variants for folder-based Luckybox heads", () => {
    const parts = {
      silver: part("luckybox_zombie/luckybox_head_silver.png"),
      gold: part("luckybox_zombie/luckybox_head_gold.png"),
      platinum: part("luckybox_zombie/luckybox_head_plat.png"),
    };
    expect(looseMutationFiles(parts, atlas).sort()).toEqual([
      "luckybox_zombie/luckybox_head_gold.png",
      "luckybox_zombie/luckybox_head_gold_flip.png",
      "luckybox_zombie/luckybox_head_plat.png",
      "luckybox_zombie/luckybox_head_plat_flip.png",
      "luckybox_zombie/luckybox_head_silver.png",
      "luckybox_zombie/luckybox_head_silver_flip.png",
    ]);
  });

  it("resolves a bare filename under assets/zombie/mutations/", () => {
    expect(looseMutationPath("cornhead.png")).toBe("mutations/cornhead.png");
    expect(looseMutationPath("cornhead")).toBe("mutations/cornhead.png");
  });

  it("takes a path with a folder as authored", () => {
    // So art kept in its own folder — including an existing mod's — resolves without
    // having to be moved or renamed.
    expect(looseMutationPath("modded_mutations/cornhead.png"))
      .toBe("modded_mutations/cornhead.png");
    expect(looseMutationPath("modded_mutations/cornhead"))
      .toBe("modded_mutations/cornhead.png");
  });
});

describe("modded zombie catalog", () => {
  const base = {
    key: "ZombieActorRegularTier1",
    name: "Plain Zombie",
    cost: 50,
    growMs: 300000,
    level: 1,
    xp: 1,
    brainsNeeded: false,
    category: "normal",
    group: "Regular",
    className: "Green",
    classColor: "#7bd84a",
    str: 2,
    dex: 2,
    con: 2,
    focus: 50,
    mutation: 0,
    tier: 1,
    marketHidden: false,
  } satisfies ZombieDef;

  it("inherits the boring fields from baseKey and keeps the mod row copy-pasteable", () => {
    expect(mergeModdedZombies([base], [{
      key: "ZombieActorRegularTier1Bread",
      name: "Bread Zombie",
      baseKey: "ZombieActorRegularTier1",
      cost: 80,
      level: 4,
      mutationIds: ["bread_neck"],
    }])).toContainEqual({
      ...base,
      key: "ZombieActorRegularTier1Bread",
      name: "Bread Zombie",
      baseKey: "ZombieActorRegularTier1",
      portraitKey: "ZombieActorRegularTier1",
      cost: 80,
      level: 4,
      category: "mutant",
      mutation: 0,
      mutationIds: ["bread_neck"],
      rewardOnly: false,
      marketHidden: false,
    });
  });
});
